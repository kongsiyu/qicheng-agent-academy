function draft(kind='normal', taskId=main, delta=-14) {
  const d = Q.blankDraft(taskId);
  Object.assign(d,{kind,date:date(delta),input:long+' '+kind+' '+date(delta),instruction:long,output:long,sourceCheck:long,correction:long,decision:long,adaptation:long,notes:long+long,support:'independent'});
  Object.keys(d.checks).forEach(k=>d.checks[k]=true);
  Object.keys(d.ratings).forEach(k=>d.ratings[k]=2);
  return d;
}
function save(kind,taskId=main,delta=-14,patch={}) {
  learning.draft=Object.assign(draft(kind,taskId,delta),patch);
  return Q.archiveRun(learning,content);
}
