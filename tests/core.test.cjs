const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const core = require('../core.js');
const Q = require('../quality-core.js');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../content.js'), 'utf8'), context);
const content = JSON.parse(JSON.stringify(context.window.AgentCourseContent));
const iso = '2026-11-16T01:00:00.000Z';
const fresh = core.createState(content);
assert.equal(fresh.schemaVersion, 2);
assert.equal(Object.keys(fresh.tasks).length, content.tasks.length);
assert.equal(fresh.profile.weeklyMinutes, 180);
assert.equal(core.getStats(fresh, content).percent, 0);
assert.equal(core.getStats(fresh, content).requiredLessons.length, content.goals.find(g => g.id === 'starter').targetLessons);
assert.equal(core.getStats(fresh, content).nextLesson.id, 'l1');
assert.equal(core.getStats(fresh, content).skills.length, 8);
const state = structuredClone(fresh);
const l1 = content.lessons[0];
state.lessons[l1.id] = { passed: true, answerIndex: l1.quiz.answerIndex, answeredAt: iso };
assert.equal(core.getStats(state, content).completedLessons, 1);
assert.equal(core.getStats(state, content).nextLesson.id, content.lessons[1].id);
assert.equal(core.getStats(state, content).skills.every(s => s.level === 0), true, 'understanding answers do not certify practical skills');
const task = content.tasks[0], taskState = state.tasks[task.id];
taskState.output = task.sampleOutput; taskState.completedAt = iso; taskState.savedAt = iso;
task.criteria.forEach(criterion => taskState.checks[criterion.id] = true);
assert.equal(core.getStats(state, content).completedTasks, 0, 'example is not independent completion');
taskState.mode = 'practice';
assert.equal(core.getStats(state, content).completedTasks, 1, 'legacy self-checked work remains accessible');
assert.equal(core.getStats(state, content).projectPercent, 0, 'legacy checkboxes do not satisfy project evidence');
taskState.checks[task.criteria[0].id] = false;
assert.equal(core.getStats(state, content).completedTasks, 0);
taskState.checks[task.criteria[0].id] = true;
state.activities = [{type:'lesson',id:l1.id,date:'2026-11-16',at:iso},{type:'task',id:task.id,date:'2026-11-16',at:iso}];
assert.equal(core.getStats(state, content).learningDays, 1);
const recorded=structuredClone(fresh), runText='使用真实资料保留一次完整的学习工作记录。';
recorded.activities=[{type:'lesson',id:l1.id,date:'2026-11-16',at:iso}];
recorded.learning.draft=Q.blankDraft(task.id);
Object.assign(recorded.learning.draft,{kind:'baseline',date:'2026-11-15',input:runText,instruction:runText,output:runText});
const historicalRun=Q.archiveRun(recorded.learning,content);
recorded.learning.draft.date='2026-11-16'; Q.archiveRun(recorded.learning,content);
assert.equal(core.getStats(recorded,content).learningDays,2,'actual run dates merge with activity dates without double counting');
recorded.learning.withdrawnRunIds.push(historicalRun.id);
assert.equal(core.getStats(recorded,content).learningDays,2,'withdrawing an outcome does not erase the historical learning day');
const before = JSON.stringify(state);
assert.deepEqual(core.normalizeState(JSON.parse(before), content, {strict:true}), state);
assert.equal(JSON.stringify(state), before, 'normalization does not mutate the source');
const old = structuredClone(state); old.schemaVersion = 1; delete old.learning;
const migrated = core.normalizeState(old, content, {strict:true});
assert.equal(migrated.schemaVersion, 2);
assert.deepEqual(migrated.tasks, old.tasks);
assert.deepEqual(migrated.lessons, old.lessons);
assert.equal(migrated.learning.runs.length, 0);
assert.equal(core.getStats(migrated, content).skills.every(s => s.level === 0), true);
assert.equal(old.schemaVersion, 1, 'migration does not mutate the legacy backup');
state.profile.goalId = 'builder';
assert.equal(core.getStats(state, content).requiredLessons.length, content.goals.find(g => g.id === 'builder').targetLessons);
state.profile.goalId = 'starter';
content.lessons.forEach(lesson => state.lessons[lesson.id] = {passed:true,answerIndex:lesson.quiz.answerIndex,answeredAt:iso});
assert.equal(core.getStats(state, content).lessonPercent, 100);
assert.equal(core.getStats(state, content).percent, 50, 'all quizzes alone can complete only the understanding half');
for (const mutate of [s=>s.schemaVersion=3,s=>s.profile.weeklyMinutes='180',s=>s.profile.startedAt='2026-02-30',s=>s.profile.unknown=true,s=>s.tasks[task.id].checks.unknown=true,s=>s.tasks[task.id].input='x'.repeat(100001),s=>delete s.learning,s=>s.learning.unknown=true,s=>s.learning.draft.ratings.s1=3]) {
  const bad = structuredClone(fresh); mutate(bad);
  assert.throws(() => core.normalizeState(bad, content, {strict:true}));
}
const disguisedLegacy = structuredClone(fresh); disguisedLegacy.schemaVersion=1;
assert.throws(() => core.normalizeState(disguisedLegacy, content, {strict:true}), /未知字段/);
const corrupt = structuredClone(fresh); corrupt.lessons.fake = {passed:true,answerIndex:0,answeredAt:iso};
assert.throws(() => core.normalizeState(corrupt, content, {strict:true}), /不存在/);
const hostile = structuredClone(fresh);
Object.defineProperty(hostile.learning.pack, '__proto__', {value:{polluted:true},enumerable:true});
assert.throws(() => core.normalizeState(hostile, content, {strict:true}), /不允许/);
assert.equal({}.polluted, undefined);
assert.equal(core.normalizeState(hostile, content).learning.runs.length, 0);
assert.match(core.today(), /^\d{4}-\d{2}-\d{2}$/);
assert.equal(core.formatDate('2026-11-15T18:00:00.000Z'), '11月16日');
assert.equal(core.formatDate('bad'), '—');
console.log('PASS: v2 state, strict v1 migration, legacy preservation without mastery, goal scope, progress separation and hostile backup rejection.');
