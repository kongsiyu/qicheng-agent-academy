const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const core = require('../core.js');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../content.js'), 'utf8'), context);
const content = JSON.parse(JSON.stringify(context.window.AgentCourseContent));
const iso = '2026-11-16T01:00:00.000Z';
const fresh = core.createState(content);
assert.equal(fresh.schemaVersion, 1);
assert.equal(Object.keys(fresh.tasks).length, 6);
assert.equal(core.getStats(fresh, content).percent, 0);
assert.equal(core.getStats(fresh, content).requiredLessons.length, 12);
assert.equal(core.getStats(fresh, content).nextLesson.id, 'l1');
assert.equal(core.getStats(fresh, content).skills.length, 6);
const state = structuredClone(fresh);
const l1 = content.lessons[0];
state.lessons[l1.id] = { passed: true, answerIndex: l1.quiz.answerIndex, answeredAt: iso };
assert.equal(core.getStats(state, content).completedLessons, 1);
assert.equal(core.getStats(state, content).nextLesson.id, 'l2');
const task = content.tasks[0];
const taskState = state.tasks[task.id];
taskState.output = task.sampleOutput;
taskState.completedAt = iso;
taskState.savedAt = iso;
task.criteria.forEach(criterion => taskState.checks[criterion.id] = true);
assert.equal(core.getStats(state, content).completedTasks, 0, 'example is not independent completion');
taskState.mode = 'practice';
assert.equal(core.getStats(state, content).completedTasks, 1);
taskState.checks[task.criteria[0].id] = false;
assert.equal(core.getStats(state, content).completedTasks, 0, 'revoked acceptance removes completion');
taskState.checks[task.criteria[0].id] = true;
taskState.output = '  ';
assert.equal(core.getStats(state, content).completedTasks, 0, 'empty results are not completed');
taskState.output = task.sampleOutput;
state.activities = [{type:'lesson',id:l1.id,date:'2026-11-16',at:iso},{type:'task',id:task.id,date:'2026-11-16',at:iso}];
assert.equal(core.getStats(state, content).learningDays, 1);
const before = JSON.stringify(state);
const restored = core.normalizeState(JSON.parse(before), content, {strict:true});
assert.deepEqual(restored, state);
assert.equal(JSON.stringify(state), before, 'normalization does not mutate the source');
assert.equal(core.getStats(restored, content).completedTasks, 1);
state.profile.goalId = 'builder';
assert.equal(core.getStats(state, content).requiredLessons.length, 15);
state.profile.goalId = 'starter';
content.lessons.forEach(lesson => state.lessons[lesson.id] = {passed:true,answerIndex:lesson.quiz.answerIndex,answeredAt:iso});
assert.equal(core.getStats(state, content).completedLessons, 12);
assert.equal(core.getStats(state, content).allCompletedLessons, 15);
assert.equal(core.getStats(state, content).lessonPercent, 100);
const corrupt = structuredClone(fresh);
corrupt.lessons.fake = {passed:true,answerIndex:0,answeredAt:iso};
assert.throws(() => core.normalizeState(corrupt, content, {strict:true}), /不存在/);
assert.equal(Object.keys(core.normalizeState(corrupt, content).lessons).length, 0);
for (const mutate of [s=>s.schemaVersion=2,s=>s.profile.weeklyMinutes='120',s=>s.profile.startedAt='2026-02-30',s=>s.profile.unknown=true,s=>s.tasks[task.id].checks.unknown=true,s=>s.tasks[task.id].input='x'.repeat(100001)]) {
  const bad = structuredClone(fresh); mutate(bad);
  assert.throws(() => core.normalizeState(bad, content, {strict:true}));
}
const hostile = JSON.parse(JSON.stringify(fresh));
Object.defineProperty(hostile.tasks, '__proto__', {value:{polluted:true},enumerable:true});
assert.throws(() => core.normalizeState(hostile, content, {strict:true}), /不允许/);
assert.equal({}.polluted, undefined);
assert.deepEqual(core.getStats(core.normalizeState(hostile, content), content).completedTaskIds, []);
assert.match(core.today(), /^\d{4}-\d{2}-\d{2}$/);
assert.equal(core.formatDate('2026-11-15T18:00:00.000Z'), '11月16日');
assert.equal(core.formatDate('bad'), '—');
console.log('PASS: real content, independent task acceptance, goal scope, restore, malformed imports, prototype defense and Shanghai dates.');
